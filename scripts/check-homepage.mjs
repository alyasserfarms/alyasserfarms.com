import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { Browser, sleep } from '../.agents/skills/design-taste-frontend/scripts/lib/cdp.mjs';

const out = 'docs/review';
mkdirSync(out, { recursive: true });
const browser = await Browser.launch();
const results = [];
const record = (name, actual, expected = true) => { assert.deepEqual(actual, expected, name); results.push({ name, passed: true }); };
try {
  const page = await browser.newPage({ width: 1440, height: 900 });
  await page.send('Page.addScriptToEvaluateOnNewDocument', { source: `window.__metrics = { lcp: 0, cls: 0 }; new PerformanceObserver(l => l.getEntries().forEach(e => window.__metrics.lcp = e.startTime)).observe({type:'largest-contentful-paint',buffered:true}); new PerformanceObserver(l => l.getEntries().forEach(e => {if(!e.hadRecentInput)window.__metrics.cls+=e.value})).observe({type:'layout-shift',buffered:true});` });
  await page.goto('http://127.0.0.1:3001', { settleMs: 2400 });
  record('Arabic RTL document', await page.eval(() => document.documentElement.lang === 'ar' && document.documentElement.dir === 'rtl'));
  record('Exactly one page heading and main landmark', await page.eval(() => document.querySelectorAll('h1').length === 1 && document.querySelectorAll('main').length === 1));
  record('All navigation anchors resolve', await page.eval(() => [...document.querySelectorAll('a[href^="#"]')].every(a => document.getElementById(a.hash.slice(1)))));
  record('Six product categories', await page.eval(() => document.querySelectorAll('.category-item').length), 6);
  record('No obsolete client name', await page.eval(() => !document.body.textContent.includes('مزرعة آل ياسر')));
  record('Approved supplied logo is rendered and loaded', await page.eval(() => { const logo = document.querySelector('.site-header .brand-name img'); return !!logo && logo.complete && logo.naturalWidth > 0 && logo.alt === 'مزارع آل ياسر'; }));
  await page.eval(() => document.querySelector('[aria-label="البحث عن منتج"]').click());
  record('Search opens a modal', await page.eval(() => document.querySelector('dialog[open]')?.getAttribute('aria-label')), 'عمّ تبحث؟');
  // Use native input editing so React sees a real input event.
  await page.eval(() => document.getElementById('product-search').focus());
  await page.send('Input.insertText', { text: 'برتقال' });
  await sleep(100);
  record('Search filters to an actual match', await page.eval(() => document.querySelectorAll('.search-results > button').length), 1);
  await page.eval(() => document.querySelector('.search-results > button').click());
  await sleep(100);
  record('Search result selects matching category', await page.eval(() => document.querySelector('.product-filters button[aria-pressed="true"]').textContent), 'الفواكه');
  await page.eval(() => document.querySelector('.product .add-button').click());
  await sleep(100);
  record('Add updates the bag count', await page.eval(() => document.querySelector('.cart-count').textContent), '1');
  await page.eval(() => { const button = document.querySelector('.cart-button'); button.focus(); button.click(); });
  record('Cart shows the selected product', await page.eval(() => document.querySelector('.cart-items h3').textContent), 'برتقال المائدة');
  await page.eval(() => document.querySelector('.quantity-controls button:last-child').click());
  await sleep(100);
  record('Quantity increment updates count and total', await page.eval(() => [document.querySelector('.cart-count').textContent, document.querySelector('.cart-summary strong').textContent]), ['2', '24']);
  await page.eval(() => document.querySelector('.cart-item-end button').click());
  await sleep(100);
  record('Remove restores empty-cart state', await page.eval(() => !!document.querySelector('.empty-cart')));
  await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  record('Escape closes the dialog', await page.eval(() => document.querySelectorAll('dialog[open]').length), 0);
  record('Dialog restores keyboard focus to its trigger', await page.eval(() => document.activeElement.classList.contains('cart-button')));
  await page.eval(() => document.querySelector('.product-filters button').click());
  await page.eval(() => document.querySelector('.product-photo-button').click());
  record('Product detail dialog opens', await page.eval(() => !!document.querySelector('dialog[open] .product-detail')));
  await page.eval(() => document.querySelector('dialog[open] .modal-heading button').click());
  record('Hero video loaded and plays', await page.eval(() => { const v = document.querySelector('.hero video'); return v.readyState >= 2 && !!v.getAttribute('src'); }));
  await page.eval(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await sleep(300);
  await page.eval(() => document.querySelector('.video-toggle').click());
  await sleep(100);
  record('Hero pause control stops playback', await page.eval(() => document.querySelector('.hero video').paused));
  await page.eval(() => window.scrollTo({ top: 1200, behavior: 'instant' }));
  await sleep(100);
  await page.eval(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await sleep(200);
  record('Manual pause persists after leaving and re-entering hero', await page.eval(() => document.querySelector('.hero video').paused));
  const performance = await page.eval(() => ({ ...window.__metrics, navigation: performance.getEntriesByType('navigation')[0]?.toJSON(), conditions: 'Local Chrome, unthrottled desktop; not field data or a mobile performance audit' }));
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewport({ width, height: 900, mobile: width < 600 });
    await page.eval(() => window.scrollTo({ top: 0, behavior: 'instant' }));
    await sleep(150);
    record(`No horizontal overflow at ${width}`, await page.eval(() => document.documentElement.scrollWidth <= window.innerWidth));
    if (width === 320) await page.screenshot({ path: `${out}/mobile-320.jpg` });
  }
  await page.eval(() => document.querySelector('[aria-label="فتح القائمة"]').click());
  record('Mobile menu opens', await page.eval(() => document.querySelector('dialog[open]')?.getAttribute('aria-label')), 'القائمة');
  await page.eval(() => document.querySelector('dialog[open] a[href="/#about"]').click());
  record('Mobile navigation closes the menu', await page.eval(() => !document.querySelector('dialog[open]')));
  const reduced = await browser.newPage({ width: 390, height: 844, mobile: true, reducedMotion: true });
  await reduced.goto('http://127.0.0.1:3001', { settleMs: 2300 });
  record('Reduced motion does not fetch hero video', await reduced.eval(() => !document.querySelector('.hero video').getAttribute('src')));
  await reduced.screenshot({ path: `${out}/mobile-reduced-motion.jpg` });
  await page.setViewport({ width: 1440, height: 900 });
  await page.eval(() => { document.querySelector('.media-credits').open = true; window.scrollTo({ top: document.documentElement.scrollHeight, behavior: 'instant' }); });
  await sleep(200);
  await page.screenshot({ path: `${out}/credits-expanded.jpg` });
  record('No uncaught browser errors', page.consoleErrors, []);
  record('No uncaught browser errors with reduced motion', reduced.consoleErrors, []);
  const report = { timestamp: new Date().toISOString(), results, performance, browserErrors: page.consoleErrors };
  writeFileSync(`${out}/interaction-results.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify({ passed: results.length, lcpMs: performance.lcp, cls: performance.cls, report: `${out}/interaction-results.json` }, null, 2));
} finally { await browser.close(); }
